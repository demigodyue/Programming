/**
 * Keeps the list of recipe slugs that accounts may save in step with the recipes (data/recipes.seed.ts):
 * - lib/recipe-slugs.ts, which the site uses to drop unknown names before saving to an account, and
 * - the RECIPE_SLUGS block in firestore.rules, which only lets those names (and 1–5 stars) into the database.
 * Slugs are only ever added, never removed, so an account that saved a dish that later goes away can still save.
 * Runs before every build (package.json "prebuild"). If the rules changed, they must be published again:
 * Firebase console → Firestore Database → Rules.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { recipesSeed } from "../data/recipes.seed";

const root = join(import.meta.dirname, "..");
const slugsFile = join(root, "lib", "recipe-slugs.ts");
const rulesFile = join(root, "firestore.rules");

let existing: string[] = [];
try {
  existing = [...readFileSync(slugsFile, "utf8").matchAll(/"([a-z0-9-]+)"/g)].map((m) => m[1]);
} catch {}
const slugs = [...new Set([...existing, ...recipesSeed.map((r) => r.slug)])].sort();

const ts = `// Generated by scripts/sync-recipe-slugs.ts from data/recipes.seed.ts (only ever grows). Do not edit by hand.
// The same list is in firestore.rules, which refuses any other name in an account's favourites or ratings.
export const RECIPE_SLUGS: ReadonlySet<string> = new Set([
${slugs.map((s) => `  "${s}",`).join("\n")}
]);
`;

const rules = readFileSync(rulesFile, "utf8");
const block = `      // RECIPE_SLUGS (generated by scripts/sync-recipe-slugs.ts)
      function recipeSlugs() {
        return [
${slugs.map((s) => `          "${s}"`).join(",\n")}
        ];
      }
      // END RECIPE_SLUGS`;
const nextRules = rules.replace(/ {6}\/\/ RECIPE_SLUGS[\s\S]*?\/\/ END RECIPE_SLUGS/, block);
if (nextRules === rules && !rules.includes("// RECIPE_SLUGS")) throw new Error("firestore.rules has no RECIPE_SLUGS block");

const oldTs = (() => {
  try {
    return readFileSync(slugsFile, "utf8");
  } catch {
    return "";
  }
})();
if (oldTs !== ts) writeFileSync(slugsFile, ts);
if (nextRules !== rules) {
  writeFileSync(rulesFile, nextRules);
  console.warn(
    "\n⚠ firestore.rules changed (new recipes). Publish it again: Firebase console → Firestore Database → Rules,\n  paste the whole file and press Publish, or saving the new dishes to an account will be refused.\n",
  );
}
console.log(`Recipe slugs: ${slugs.length}`);
